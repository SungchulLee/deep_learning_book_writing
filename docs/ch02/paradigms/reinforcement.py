"""강화학습의 네 정리를 수로 확인한다.

    정리 1  gamma < 1 이면 할인 수익이 유한하고 그 위 끝이 R_max/(1-gamma)
    정리 2  gamma가 작으면 가까운 보상이, 크면 먼 보상이 이긴다
    정리 3  관측을 상태로 쓰면 최적을 놓친다
    정리 4  탐색이 없으면 후회가 T에 비례해 는다

본문이 "gamma ~ 0.9 부근"과 "후회도 수십 수준"이라고 어림한 두 자리를
코드는 정확히 짚어 준다.
"""

import numpy as np


# ==========================================================================
# 정리 1 — 할인 수익은 유한하고, 유효 시야는 1/(1-gamma)
# ==========================================================================
print("=" * 64)
print("정리 1  할인 수익의 유한성과 유효 시야")
print("=" * 64)
print(f"  {'gamma':>6} | {'유한 합(t<10000)':>16} | {'1/(1-gamma)':>12} | {'유효 시야':>9}")
print("  " + "-" * 52)

for gamma in (0.5, 0.9, 0.99, 0.999):
    # 보상이 늘 1일 때의 할인 수익을 직접 더해 본다
    t = np.arange(10000)
    numeric = (gamma ** t).sum()
    closed = 1.0 / (1.0 - gamma)          # 정리 1이 말하는 위 끝
    print(f"  {gamma:>6} | {numeric:>16.4f} | {closed:>12.4f} | {closed:>9.1f}걸음")

print("\n  더한 값과 닫힌 꼴이 소수점 아래까지 같다.")
print("  1/(1-gamma)는 '몇 걸음 앞까지 내다보는가'로 읽힌다.")


# ==========================================================================
# 정리 2 — gamma가 두 방침의 순위를 뒤집는다
# ==========================================================================
print("\n" + "=" * 64)
print("정리 2  가까운 보상 대 먼 보상 — gamma가 순위를 정한다")
print("=" * 64)


def V1(g):
    """방침 1: t=0,1 에서 보상 1. 곧 1 + gamma."""
    return 1.0 + g


def V2(g):
    """방침 2: t=15..54 에서 보상 1. 곧 gamma^15 (1-gamma^40)/(1-gamma)."""
    return g ** 15 * (1 - g ** 40) / (1 - g)


print(f"  {'gamma':>6} | {'V1':>8} | {'V2':>8} | 이기는 쪽")
print("  " + "-" * 40)
for g in (0.5, 0.7, 0.8, 0.9, 0.95, 0.99):
    a, b = V1(g), V2(g)
    print(f"  {g:>6} | {a:>8.4f} | {b:>8.4f} | {'방침 2' if b > a else '방침 1'}")

# 본문은 뒤바뀌는 자리를 "gamma ~ 0.9 부근"이라 적었다. 이분법으로 정확히 찾는다.
lo, hi = 0.5, 0.999
for _ in range(60):                       # 60번이면 배정도가 다 찬다
    mid = (lo + hi) / 2
    if V2(mid) > V1(mid):                 # 방침 2가 이기면 더 작은 gamma로
        hi = mid
    else:
        lo = mid
print(f"\n  순위가 뒤바뀌는 자리: gamma = {(lo + hi) / 2:.6f}")
print(f"    그 자리에서 V1 = {V1((lo+hi)/2):.4f}, V2 = {V2((lo+hi)/2):.4f}")


# ==========================================================================
# 정리 3 — 관측을 상태로 쓰면 최적을 놓친다
# ==========================================================================
print("\n" + "=" * 64)
print("정리 3  부분 관측의 대가")
print("=" * 64)

# 가장 작은 반례를 만든다.
#   상태가 둘(s0, s1)인데 관측은 하나(o)뿐이다 — 곧 둘을 구별할 수 없다.
#   s0에서는 행동 a가, s1에서는 행동 b가 옳다.
#   두 상태가 반반으로 나온다.
REWARD = {("s0", "a"): 1.0, ("s0", "b"): 0.0,     # s0에서는 a가 옳다
          ("s1", "a"): 0.0, ("s1", "b"): 1.0}     # s1에서는 b가 옳다
STATES = ["s0", "s1"]
P_STATE = {"s0": 0.5, "s1": 0.5}

# 상태를 볼 수 있다면: 상태마다 제일 좋은 행동을 고른다
v_state = sum(P_STATE[s] * max(REWARD[(s, a)] for a in "ab") for s in STATES)

# 관측만 본다면: 두 상태가 똑같이 보이므로 **하나의 행동**을 써야 한다
v_obs = max(sum(P_STATE[s] * REWARD[(s, a)] for s in STATES) for a in "ab")

print(f"  상태를 볼 수 있을 때의 값 : {v_state:.2f}")
print(f"  관측만 볼 때의 값         : {v_obs:.2f}")
print(f"  부분 관측이 치르는 값     : {v_state - v_obs:.2f}")
print("\n  관측이 같으면 행동도 같아야 하므로, 절반에서 반드시 틀린다.")
print("  기억을 두어 과거를 쌓으면 이 손해를 줄일 수 있다(그래서 RNN을 쓴다).")


# ==========================================================================
# 정리 4 — 탐색이 없으면 후회가 T에 비례한다
# ==========================================================================
print("\n" + "=" * 64)
print("정리 4  탐색 없는 방침의 후회 (보기 3을 실제로 돌려 본다)")
print("=" * 64)

MU = np.array([0.6, 0.5])                 # 팔 둘의 참 성공률
T = 1000
N_RUN = 200000
rng = np.random.RandomState(0)

# 방침: 팔마다 한 번씩 당겨 보고, 더 좋아 보인 팔을 T걸음 끝까지 쥔다.
#   비긴 경우에는 동전을 던져 고른다.
r0 = (rng.rand(N_RUN) < MU[0]).astype(int)      # 팔 1의 첫 보상
r1 = (rng.rand(N_RUN) < MU[1]).astype(int)      # 팔 2의 첫 보상
coin = rng.rand(N_RUN) < 0.5
chosen = np.where(r1 > r0, 1, np.where(r0 > r1, 0, coin.astype(int)))

p_stuck = (chosen == 1).mean()             # 나쁜 팔에 갇힐 확률
delta = MU[0] - MU[1]                      # 걸음마다의 손해
# 후회 = (최적 팔로 T걸음) - (실제로 얻은 기대 보상). 첫 두 걸음은 탐색이라 빼 둔다.
regret = np.where(chosen == 1, delta * (T - 2), 0.0).mean() + delta  # 탐색 한 걸음의 손해

print(f"  참 성공률 mu = {MU},  Delta = {delta:.1f},  T = {T}")
print(f"  실험 횟수 {N_RUN:,}번\n")
print(f"  나쁜 팔에 갇힌 비율 p        = {p_stuck:.4f}")
print(f"  이론값 p                     = {0.4*0.5 + 0.5*(0.4*0.5 + 0.6*0.5):.4f}"
      f"   (r2>r1 이거나, 비겨서 동전이 팔 2를 고를 때)")
print(f"  잰 평균 후회 Reg({T})       = {regret:.2f}")
print(f"  본문의 어림 100p             = {100 * p_stuck:.2f}")

# T를 키우면 후회가 정말 T에 비례하는가
print(f"\n  {'T':>6} | {'잰 후회':>9} | {'후회/T':>8}")
print("  " + "-" * 30)
for t in (100, 1000, 10000, 100000):
    reg = np.where(chosen == 1, delta * (t - 2), 0.0).mean() + delta
    print(f"  {t:>6} | {reg:>9.2f} | {reg/t:>8.5f}")

print("\n  후회/T가 거의 일정하다 -> 후회가 T에 **비례**한다(선형). 정리 4가 말한 대로다.")
print("  탐색을 넣은 방법(UCB 따위)은 이 값이 T가 커질수록 0으로 간다.")
