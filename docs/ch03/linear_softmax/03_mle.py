"""표지-재포획 가능도를 끝까지 셈해 본문의 수를 하나씩 확인한다.

본문은 값을 꽤 많이 적어 두었다. P_7 = 0.143, P_12 = 0.4773,
P_18 = 0.4779, P_50 = 0.2526, 비의 가장 낮은 값 0.9777 (N=25),
그리고 14와 15가 비긴다는 것. 모두 셈해서 맞춰 본다.

마지막에는 4절의 주장 — "MNIST에서는 이대로 못 한다" — 이 얼마나
큰 이야기인지도 수로 적어 둔다.
"""

from math import comb, log10

# 문제의 설정: 3마리를 표지해 놓아주고, 나중에 5마리를 잡아 1마리가 표지였다
M, N_CATCH, K = 3, 5, 1


# ==========================================================================
# 가능도 — 초기하분포
# ==========================================================================
def likelihood(N):
    """호수에 N마리가 있을 때 '5마리 중 표지 1마리'가 나올 확률.

    분자: 표지된 M마리에서 K마리, 표지 없는 N-M마리에서 나머지를 고른다
    분모: N마리에서 N_CATCH마리를 고르는 모든 경우
    """
    if N - M < N_CATCH - K:          # 표지 없는 물고기가 모자라면 불가능
        return 0.0
    return comb(M, K) * comb(N - M, N_CATCH - K) / comb(N, N_CATCH)


print("=" * 60)
print("가능도를 N에 대해 펼친다")
print("=" * 60)
print(f"  설정: 표지 {M}마리, 나중에 {N_CATCH}마리를 잡아 {K}마리가 표지\n")
print(f"  {'N':>4} | {'P_N':>8} | {'P_(N+1)/P_N':>12} |")
print("  " + "-" * 32)

for N in list(range(7, 21)) + [25, 30, 50]:
    p = likelihood(N)
    ratio = likelihood(N + 1) / p if p > 0 else float("nan")
    star = "  <- 봉우리" if N in (14, 15) else ""
    print(f"  {N:>4} | {p:>8.4f} | {ratio:>12.4f} |{star}")


# ==========================================================================
# 본문이 적어 둔 값들을 하나씩 맞춰 본다
# ==========================================================================
print("\n" + "=" * 60)
print("본문의 수와 맞는가")
print("=" * 60)

checks = [
    ("P_7  = 1/7",            likelihood(7),           1 / 7),
    ("P_12",                  likelihood(12),          0.4773),
    ("P_18",                  likelihood(18),          0.4779),
    ("P_50",                  likelihood(50),          0.2526),
    ("P_14 = P_15 (비김)",     likelihood(14),          likelihood(15)),
]
for name, got, want in checks:
    ok = "맞다" if abs(got - want) < 5e-4 else "다르다"
    print(f"  {name:<22} 셈한 값 {got:.4f}   적힌 값 {want:.4f}   {ok}")

# 봉우리가 정말 14, 15인지 전부 훑어 확인한다
best = max(range(7, 2000), key=likelihood)
tied = [N for N in range(7, 2000) if abs(likelihood(N) - likelihood(best)) < 1e-12]
print(f"\n  7부터 1999까지 훑어 가장 큰 N: {tied}   (둘이 비긴다)")

# 링컨-피터슨 어림값 mn/k 와 견준다
print(f"  링컨-피터슨 mn/k = {M}x{N_CATCH}/{K} = {M*N_CATCH//K}")
print(f"    정수이므로 {M*N_CATCH//K - 1}과 {M*N_CATCH//K}가 비긴다 — 본문과 같다.")


# ==========================================================================
# 비의 꼴을 손으로 편 식과 맞춰 본다
# ==========================================================================
print("\n" + "=" * 60)
print("비 P_(N+1)/P_N 이 (N-2)(N-4)/((N-6)(N+1)) 과 같은가")
print("=" * 60)

worst = 0.0
for N in range(7, 500):
    direct = likelihood(N + 1) / likelihood(N)
    formula = (N - 2) * (N - 4) / ((N - 6) * (N + 1))
    worst = max(worst, abs(direct - formula))
print(f"  N = 7..499 에서 가장 큰 차이: {worst:.2e}   (0이라야 한다)")

# 비가 가장 낮은 자리 — 본문은 N=25에서 0.9777이라 했다
lo = min(range(7, 200), key=lambda N: likelihood(N + 1) / likelihood(N))
print(f"  비가 가장 낮은 자리: N = {lo},  그때 비 = "
      f"{likelihood(lo+1)/likelihood(lo):.4f}")
print("  그 뒤로는 다시 1 쪽으로 올라간다 — 꼬리가 끝내 끊기지 않는 까닭이다.")


