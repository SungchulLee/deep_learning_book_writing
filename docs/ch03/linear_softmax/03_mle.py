# 표본을 늘리면 봉우리가 뾰족해지는가 (연습문제 5)
# ==========================================================================
print("\n" + "=" * 60)
print("표본을 늘리면 봉우리가 뾰족해지는가")
print("=" * 60)

def peak_and_width(m, n, k):
    """표지 m, 재포획 n, 그중 표지 k 일 때의 봉우리와 '헐거움'."""
    def L(N):
        if N < m or N - m < n - k or n > N:
            return 0.0
        return comb(m, k) * comb(N - m, n - k) / comb(N, n)
    Ns = range(max(m, n), 6000)
    best = max(Ns, key=L)
    top = L(best)
    # 가능도가 최댓값의 절반을 넘는 N의 범위 = 봉우리의 폭
    wide = [N for N in Ns if L(N) >= top / 2]
    return best, min(wide), max(wide)

# 표본을 키우되 **호수의 크기는 그대로**여야 한다.
#
# 참 N이 15뿐이면 표본을 키울 자리가 없다 — 표지도 재포획도 15를 넘을 수
# 없고, 되잡힌 표지 수 k는 표지 수 m보다 클 수 없기 때문이다. 그래서
# 호수를 크게 잡고(N = 1000) 그 안에서 표본만 키운다.
#
# 참 N이 1000이면 표지 m, 재포획 n에서 기대되는 표지 수는 k = m*n/1000 이다.
# 그래야 링컨-피터슨 어림 mn/k 가 1000에 머문 채 표본만 커진다.
TRUE_N = 1000
print(f"  참 마릿수를 {TRUE_N}로 두고, 어림이 {TRUE_N}에 머물도록 표본만 키운다\n")
print(f"  {'표지':>5} {'재포획':>6} {'표지된 것':>8} | {'mn/k':>6} | {'봉우리':>6} | "
      f"{'절반 넘는 범위':>16} | {'폭':>6}")
print("  " + "-" * 68)
for m, n in ((100, 100), (200, 200), (400, 400), (600, 600)):
    k = m * n // TRUE_N                       # 기대되는 되잡힘 수
    b, lo_, hi_ = peak_and_width(m, n, k)
    print(f"  {m:>5} {n:>6} {k:>8} | {m*n//k:>6} | {b:>6} | "
          f"{lo_:>6} ~ {hi_:<7} | {hi_-lo_:>6}")

print("\n  어림값(mn/k)은 1000에 그대로 머무는데 '절반 넘는 범위'가 좁아진다.")
print("  표본이 커질수록 자료가 답을 더 좁게 집어 준다 — 봉우리가 뾰족해지는 것이다.")


